<script>
    // Ensure jQuery is loaded before execution
    $(document).ready(function() {
        const carouselId = '#refactoredCarousel';
        const $carousel = $(carouselId);
        let slideTimer;

        // --- Custom Animation Logic (Kept for visual appeal) ---

        // Function to apply animations (FadeInUp/Down/Left/Right)
        function animateActiveSlide(slide) {
            // Reset state
            slide.querySelectorAll('.refactored-badge, .refactored-content h1, .refactored-content p, .btn-primary-glow').forEach(el => {
                el.style.opacity = '0';
                el.style.transform = 'translateY(20px)';
                el.style.transition = 'none'; // Disable transition for reset
            });

            // Animate elements with staggered delay
            const elementsToAnimate = [
                slide.querySelector('.refactored-badge'),
                slide.querySelector('.refactored-content h1'),
                slide.querySelector('.refactored-content p'),
                slide.querySelector('.btn-primary-glow')
            ].filter(el => el != null); // Filter out null elements

            elementsToAnimate.forEach((el, index) => {
                setTimeout(() => {
                    el.style.transition = 'opacity 0.8s ease, transform 0.8s ease';
                    el.style.opacity = '1';
                    el.style.transform = 'translateY(0)';
                }, 50 + index * 200); // Staggered delay
            });
        }

        // --- Custom Interval Logic (Kept as before) ---

        // 1. Initialize the carousel instance without the default interval
        $carousel.carousel({
            interval: false, // Prevents built-in auto-cycling
            pause: 'hover'
        });

        // Function to start the timer for the active slide
        function startSlideTimer() {
            clearTimeout(slideTimer); // Clear any existing timer

            const $activeSlide = $carousel.find('.carousel-item.active');
            // Get the custom interval from data-slide-interval attribute, default to 5000ms
            const interval = parseInt($activeSlide.attr('data-slide-interval')) || 5000;

            // Start the timer to transition to the next slide
            slideTimer = setTimeout(function() {
                $carousel.carousel('next');
            }, interval);
        }

        // 2. Initial animation and timer start on page load
        const initialActiveSlide = $carousel.find('.carousel-item.active')[0];
        animateActiveSlide(initialActiveSlide);
        startSlideTimer();


        // 3. Event listener for when a slide finishes transitioning
        $carousel.on('slid.bs.carousel', function (event) {
            animateActiveSlide(event.relatedTarget);
            startSlideTimer();
        });

        // 4. Handle Pause/Resume on mouseenter/mouseleave
        $carousel.on('mouseenter', function() {
            clearTimeout(slideTimer);
        }).on('mouseleave', function() {
            startSlideTimer();
        });


        // --- 📱 FIXED MOBILE SWIPE LOGIC ---
        let touchStartPos = null;
        const sensitivity = 50; // Increased sensitivity to require a more deliberate swipe

        $carousel.on('touchstart', function(event) {
            // Check if touch event exists and get starting X position
            if (event.originalEvent.touches && event.originalEvent.touches.length) {
                touchStartPos = event.originalEvent.touches[0].pageX;
            }
        });

        $carousel.on('touchmove', function(event) {
            if (touchStartPos !== null && event.originalEvent.touches && event.originalEvent.touches.length) {
                const touchEndPos = event.originalEvent.touches[0].pageX;
                const deltaX = touchStartPos - touchEndPos;

                // Prevent vertical scrolling while swiping horizontally
                if (Math.abs(deltaX) > Math.abs(event.originalEvent.touches[0].pageY - event.originalEvent.touches[0].clientY)) {
                    event.preventDefault();
                }

                // If the movement is significant, trigger the slide and reset touchStartPos
                if (deltaX > sensitivity) { // Swipe Left (Next slide)
                    $carousel.carousel('next');
                    touchStartPos = null; // Reset to prevent multiple slides on one swipe
                } else if (deltaX < -sensitivity) { // Swipe Right (Previous slide)
                    $carousel.carousel('prev');
                    touchStartPos = null; // Reset to prevent multiple slides on one swipe
                }
            }
        });

        $carousel.on('touchend', function() {
            // Reset position on touchend, regardless of whether a swipe occurred
            touchStartPos = null;
        });
        // --- END FIXED MOBILE SWIPE LOGIC ---

    });
</script>
