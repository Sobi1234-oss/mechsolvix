<script>
    document.addEventListener("DOMContentLoaded", () => {
  // Get all sliders (mobile and desktop)
  const mobileSlides = document.querySelector('.cap-mobile-slider') ?
                      document.querySelector('.cap-mobile-slider').querySelectorAll(".cap-slide") : [];
  const desktopSlides = document.querySelector('.cap-right') ?
                       document.querySelector('.cap-right').querySelectorAll(".cap-slide") : [];

  let mobileCurrent = 0;
  let desktopCurrent = 0;

  // Mobile slider controls
  const mobileNext = document.querySelector('.cap-mobile-slider') ?
                    document.querySelector('.cap-mobile-slider').querySelector(".cap-next") : null;
  const mobilePrev = document.querySelector('.cap-mobile-slider') ?
                    document.querySelector('.cap-mobile-slider').querySelector(".cap-prev") : null;

  // Desktop slider controls
  const desktopNext = document.querySelector('.cap-right') ?
                     document.querySelector('.cap-right').querySelector(".cap-next") : null;
  const desktopPrev = document.querySelector('.cap-right') ?
                     document.querySelector('.cap-right').querySelector(".cap-prev") : null;

  function showSlide(slides, current, index) {
    slides.forEach(s => s.classList.remove("active"));
    slides[index].classList.add("active");
    return index;
  }

  // Mobile slider functionality
  if (mobileSlides.length > 0 && mobileNext && mobilePrev) {
    mobileNext.onclick = () => {
      mobileCurrent = (mobileCurrent + 1) % mobileSlides.length;
      mobileCurrent = showSlide(mobileSlides, mobileCurrent, mobileCurrent);
    };

    mobilePrev.onclick = () => {
      mobileCurrent = (mobileCurrent - 1 + mobileSlides.length) % mobileSlides.length;
      mobileCurrent = showSlide(mobileSlides, mobileCurrent, mobileCurrent);
    };

    // Auto-slide for mobile (only 4 slides)
    setInterval(() => {
      mobileCurrent = (mobileCurrent + 1) % mobileSlides.length;
      mobileCurrent = showSlide(mobileSlides, mobileCurrent, mobileCurrent);
    }, 4000);
  }

  // Desktop slider functionality
  if (desktopSlides.length > 0 && desktopNext && desktopPrev) {
    desktopNext.onclick = () => {
      desktopCurrent = (desktopCurrent + 1) % desktopSlides.length;
      desktopCurrent = showSlide(desktopSlides, desktopCurrent, desktopCurrent);
    };

    desktopPrev.onclick = () => {
      desktopCurrent = (desktopCurrent - 1 + desktopSlides.length) % desktopSlides.length;
      desktopCurrent = showSlide(desktopSlides, desktopCurrent, desktopCurrent);
    };

    // Auto-slide for desktop (8 slides)
    setInterval(() => {
      desktopCurrent = (desktopCurrent + 1) % desktopSlides.length;
      desktopCurrent = showSlide(desktopSlides, desktopCurrent, desktopCurrent);
    }, 4500);
  }
});
</script>
