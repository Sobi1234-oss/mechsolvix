<script>
    // -------------------------------------------
    // SLIDER JAVASCRIPT (To make the slides transition)
    // -------------------------------------------
    document.addEventListener('DOMContentLoaded', () => {
        const sliderContainer = document.getElementById('featuresCompactSlider');
        const slides = sliderContainer.querySelectorAll('.features-slider-slide');
        const totalSlidesDisplay = document.querySelector('.features-total-slides');
        const currentSlideDisplay = document.querySelector('.features-current-slide');
        const prevBtn = document.querySelector('.features-prev-btn');
        const nextBtn = document.querySelector('.features-next-btn');
        const dotsContainer = document.querySelector('.features-control-dots');
        let currentIndex = 0;

        // Set total slides count
        if (totalSlidesDisplay) {
            totalSlidesDisplay.textContent = String(slides.length).padStart(2, '0');
        }

        function updateSlider(newIndex) {
            // Loop the index
            if (newIndex >= slides.length) {
                newIndex = 0;
            } else if (newIndex < 0) {
                newIndex = slides.length - 1;
            }

            // Hide all slides and remove active class
            slides.forEach((slide, index) => {
                slide.classList.remove('active');
                slide.style.opacity = '0';
                slide.style.position = 'absolute';
            });

            // Show the new active slide
            slides[newIndex].classList.add('active');
            slides[newIndex].style.opacity = '1';
            slides[newIndex].style.position = 'relative';

            currentIndex = newIndex;

            // Update controls
            if (currentSlideDisplay) {
                currentSlideDisplay.textContent = String(currentIndex + 1).padStart(2, '0');
            }
            updateDots();
        }

        function updateDots() {
            const dots = dotsContainer.querySelectorAll('.features-control-dot');
            dots.forEach((dot, index) => {
                dot.classList.toggle('active', index === currentIndex);
            });
        }

        // Initial setup for dots and first slide
        updateDots();
        slides[currentIndex].style.opacity = '1';
        slides[currentIndex].style.position = 'relative';

        // Event listeners for buttons
        nextBtn.addEventListener('click', () => {
            updateSlider(currentIndex + 1);
        });

        prevBtn.addEventListener('click', () => {
            updateSlider(currentIndex - 1);
        });

